echo "== the gate SET is fully wired -- no gate exists that nothing runs =="
# Round 12 found shell-syntax.sh absent from `composer gate` one commit after it was added and documented as
# FIRST in the gate command block. The reason it went unnoticed is that the clean-fixture block above is a
# HAND-WRITTEN list of assert_gate lines, and this repo already learned -- for the licence-rule documents --
# that "a hand-listed loop cannot notice a seventh surface appearing". So the set is compared against the
# filesystem rather than against anybody's memory.
gates_on_disk="$(cd "$REPO_ROOT/scripts/gates" && ls -1 *.php *.sh 2>/dev/null | grep -v '^test-gates.sh$' | sort | tr '\n' ' ')"

# a) every gate on disk has a clean-fixture case in THIS suite
#
# A gate may declare its clean case ELSEWHERE, and the redirect is VERIFIED rather than trusted. One gate needs a
# database -- `schema-tenancy.php` reads a real migrated schema, which is the whole point of it -- and this suite
# runs on plain PHP with no server, so requiring its clean case here would mean the entire meta-suite stops
# whenever PostgreSQL is down.
#
# The redirect is NOT an exemption, and the distinction matters: § Gotchas records "an exemption inside a
# cross-check is where the drift hides", where `THIRD-PARTY-NOTICES.md` was excused from half a licence check and
# then contradicted the gate in its own rule statement. So a redirect must name a FILE and a TEST, and both are
# checked to exist -- if the test is renamed or deleted, this case fails exactly as a missing local case would.
#
# Format, one per line, anywhere in this file:
#   # clean-case-elsewhere: <gate file> <path relative to repo root> <test method substring>
# clean-case-elsewhere: schema-tenancy.php api/tests/Integration/Tenancy/SchemaTenancyGateTest.php testTheGateAcceptsTheSchemaOurMigrationProduces
missing_case=""
for gate in $gates_on_disk; do
  if grep -qF "assert_gate \"clean: ${gate%%.*}" "$REPO_ROOT/scripts/gates/test-gates.sh" \
    || grep -qF "$gate 0" "$REPO_ROOT/scripts/gates/test-gates.sh"; then
    continue
  fi

  redirect="$(grep -E "^# clean-case-elsewhere: ${gate} " "$REPO_ROOT/scripts/gates/test-gates.sh" | head -1)"

  if [[ -n "$redirect" ]]; then
    redirect_file="$(printf '%s' "$redirect" | awk '{print $4}')"
    redirect_test="$(printf '%s' "$redirect" | awk '{print $5}')"

    # ANCHOR ON THE DECLARATION, never a substring. A plain `grep -qF` on the method name is satisfied by the name
    # appearing in a COMMENT, so the test method could be DELETED -- leaving only a docblock that mentions it --
    # and this suite still reported 366 passed, 0 failed. A reviewer proved exactly that at 8f85b2d, which made
    # this the same shape as `test-gates.sh` once reporting 33/33 for a gate that detected nothing, one level up.
    # Four surfaces claimed the redirect could not be a hiding place; none of them was true.
    if [[ -f "$REPO_ROOT/$redirect_file" ]] \
      && grep -qE "function[[:space:]]+${redirect_test}[[:space:]]*\(" "$REPO_ROOT/$redirect_file"; then
      printf '  ok   — %s clean case is verified at %s::%s\n' "$gate" "$redirect_file" "$redirect_test"
      passed=$((passed + 1))
      continue
    fi

    printf '  FAIL — %s redirects its clean case to %s::%s, which does not exist\n' \
      "$gate" "$redirect_file" "$redirect_test"
    failed=$((failed + 1))
    continue
  fi

  missing_case="$missing_case $gate"
done

if [[ -z "$missing_case" ]]; then
  printf '  ok   — %s\n' 'every gate on disk has a clean-fixture case here'
  passed=$((passed + 1))
else
  printf '  FAIL — %s (%s)\n' 'a gate on disk has no case in this suite' "$missing_case"
  failed=$((failed + 1))
fi

# b) every gate on disk is RUN by composer gate:architecture (or gate:licences for the licensing one).
#    A gate nobody runs is not a gate -- and the documented one-command entry point is `composer gate`.
# Parsed from the `scripts` OBJECT, never grepped from the file. The first version of this case grepped
# composer.json whole, and the mutant that unwires shell-syntax SURVIVED it -- because the gate's name also
# appears in `scripts-descriptions`, which is prose that runs nothing. A check that greps a file instead of
# the thing that executes is the defect this repository records more than any other, and this case reproduced
# it on its first attempt.
runnable="$(php -r '
    $d = json_decode(file_get_contents($argv[1]), true);
    $out = [];
    array_walk_recursive($d["scripts"], function ($v) use (&$out) { $out[] = $v; });
    echo implode("\n", $out);
' "$REPO_ROOT/api/composer.json")"

missing_wiring=""
for gate in $gates_on_disk; do
  printf '%s' "$runnable" | grep -qF "$gate" || missing_wiring="$missing_wiring $gate"
done

if [[ -z "$missing_wiring" ]]; then
  printf '  ok   — %s\n' 'every gate on disk is wired into composer gate'
  passed=$((passed + 1))
else
  printf '  FAIL — %s (%s)\n' 'a gate on disk is run by no composer script' "$missing_wiring"
  failed=$((failed + 1))
fi

# c) ANTI-VACUITY: the two loops above are silent if the directory listing is empty, which is exactly how
#    this class of case passes while checking nothing.
if [[ -n "$gates_on_disk" ]]; then
  printf '  ok   — %s (%s)\n' 'the gate inventory is non-empty' "$(printf '%s' "$gates_on_disk" | wc -w) gates"
  passed=$((passed + 1))
else
  printf '  FAIL — %s\n' 'the gate inventory is EMPTY, so both checks above were vacuous'
  failed=$((failed + 1))
fi

assert_at_least "the suite itself has not shrunk" "$passed" 330

